def matches(name, title):
    return name == title or name.startswith(title + '.')

def main(reclassify=True):
    plan=json.loads(PLAN.read_text())
    for i,row in enumerate(plan['items'] if reclassify else [],1):
        row['id']=f'route-{i:04}'
        if row['status']=='ignore': continue
        row.update(status='review',proposed_path=None,reason='现有资料不足以锁定叙事重心或身份，原地保留待讨论。',sources=[],evidence='待核验')
        candidates=[]
        for dest,titles in GROUPS[row['category']].items():
            for title in titles.split('|'):
                if matches(row['name'],title): candidates.append((dest,title))
        if len(candidates)>1: raise ValueError((row['name'],candidates))
        if candidates:
            dest,title=candidates[0]
            row.update(status='planned', proposed_path=str(Path(plan['root'])/dest/row['name']),reason=REASONS[dest], evidence='基于已知剧情的分类判断，未逐片联网复核')
        if matches(row['name'],'十三岁'):
            row.update(status='planned',proposed_path=str(Path(plan['root'])/'青春'/row['name']),evidence='基于已知剧情的分类判断，未逐片联网复核')
        if any(matches(row['name'],t) for t in ['上学路上','史前之旅','于是我将奔向世界尽头']):
            row.update(status='review',proposed_path=None,evidence='待核验')
        for title,note in NOTES.items():
            if matches(row['name'],title): row['reason']=note
        for title,url in SOURCES.items():
            if matches(row['name'],title): row['sources']=[url];row['evidence']='本轮联网核对；归类仍为本报告判断'
    if reclassify:
        plan['rules']=RULES
        PLAN.write_text(json.dumps(plan,ensure_ascii=False,indent=2)+'\n')
    digest=hashlib.sha256(PLAN.read_bytes()).hexdigest()
    items=plan['items']; active=[r for r in items if r['status']!='ignore']
    lines=['# 分类细化审阅报告','',f"扫描时间：{plan['generated_at']}",'','状态：只读扫描与方案生成完成；NAS 未移动、改名、删除或新建目录。',
      '',f"五个目录共 {len(items)} 个直接条目，其中 {len(active)} 个非隐藏条目、{len(items)-len(active)} 个隐藏项。条目包含影片目录，不等于影片部数。",'',
      '## 已确认的规则','',RULES,'',
      '## 如何审核与执行','',
      '“拟执行”是本报告建议，尚未获得执行授权；“待讨论”没有目标路径，程序始终跳过。已知剧情判断与本轮联网核验分别标注，不能把所有建议理解为已逐片查证。',
      '本轮不重命名片名，不合并目录，不拆分目录内部多段/字幕/花絮，不删除原分类目录。旧目录可能因待讨论项及隐藏文件继续存在。',
      '报告和程序共用分类计划.json；执行程序不会调用模型或重新查剧情。审核修改后，重新生成报告及计划摘要；不要运行生成报告.py覆盖人工调整，应使用执行程序的 --report 选项。',
      '', '## 数量汇总','', '| 原目录 | 拟执行 | 待讨论 | 隐藏项跳过 |','|---|---:|---:|---:|']
    for c in plan['categories']:
        n=Counter(r['status'] for r in items if r['category']==c)
        lines.append(f"| {c} | {n['planned']} | {n['review']} | {n['ignore']} |")
    lines+=['','拟执行目标：'+ '；'.join(f'{c} {n}' for c,n in sorted(Counter(Path(r['proposed_path']).parent.name for r in items if r['status']=='planned').items())),
      '', '## 优先审阅的边界项','']
    for row in active:
        if any(matches(row['name'],t) for t in NOTES):
            dest=Path(row['proposed_path']).parent.name if row['proposed_path'] else '待讨论'
            lines.append(f"- **{row['name']}** → {dest}：{row['reason']}")
    for c in plan['categories']:
        lines+=['',f'## {c}','', '| ID | 原文件或目录名 | 建议去向 | 状态 | 理由 | 依据 |','|---|---|---|---|---|---|']
        for r in active:
            if r['category']!=c: continue
            dest=Path(r['proposed_path']).parent.name if r['proposed_path'] else '原地保留'
            evidence='；'.join(f'[来源]({s})' for s in r['sources']) or r['evidence']
            vals=[r['id'],r['name'],dest,'拟执行' if r['status']=='planned' else '待讨论',r['reason'],evidence]
            lines.append('| '+' | '.join(v.replace('|','\\|').replace('\n',' ') for v in vals)+' |')
    lines+=['','## 执行入口','', '默认预演（只读，不写 NAS）：','', '```bash',f'python3 "{BASE}/执行分类.py"','```','',
      '审核通过后才使用下面的命令。摘要锁定本版 JSON，计划被修改后旧命令会失效。执行前会全量预检，发现来源变化、目标冲突、路径越界或符号链接即停止；执行后逐项核对，并写本地日志。','',
      '```bash',f'python3 "{BASE}/执行分类.py" --execute --plan-sha256 {digest}','```','',f'计划 SHA-256：`{digest}`','',
      '## 验证边界','',
      '文件核对使用相对路径、大小、纳秒修改时间；目录整体同卷移动后逐项读回。没有读取全部视频做内容哈希，也没有验证影片实际画面与文件名一致。新增/缺失的非隐藏直接条目会阻止执行；待讨论目录内部不作为本次移动对象。']
    (BASE/'分类细化报告.md').write_text('\n'.join(lines)+'\n')
    print(dict(Counter(r['status'] for r in items)),digest)

if __name__=='__main__': main()
